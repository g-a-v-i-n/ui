/**
 * Generate the tier-1 color scales for ui/src/css from @radix-ui/colors.
 *
 * Radix ships each scale as separate light and dark stylesheets keyed to a
 * `.dark` class. The library instead switches modes through `color-scheme`
 * (set by the `data-theme` attribute, or the OS preference when it is absent),
 * so every step is written once as `light-dark(<light>, <dark>)` and resolves
 * wherever it is used — on the page, or inside a nested `data-theme` subtree.
 *
 * Writes:
 *   ui/src/css/scales.css     --<scale>-1…12 and --<scale>-a1…a12 for every
 *                             scale below, plus the fixed --black-a* / --white-a*.
 *   ui/src/css/gray-tone.css  [data-gray="<tone>"] blocks that re-point
 *                             --gray-* at a tinted gray.
 *
 * Run: pnpm generate-color-scales   (Node >= 22.18 strips TS types natively)
 */
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as radix from "@radix-ui/colors";

const CSS_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../ui/src/css");

/** Tinted grays that data-gray can swap in for --gray-*. */
const GRAY_TONES = ["mauve", "slate", "sage", "olive", "sand"] as const;

/** Every scale the library's tokens reference. */
const SCALES = [
  "gray",
  ...GRAY_TONES,
  "red",
  "amber",
  "tomato",
  "purple",
  "teal",
  "blue",
  "pink",
  "crimson",
  "grass",
  "lime",
  "violet",
] as const;

const STEPS = Array.from({ length: 12 }, (_, i) => i + 1);

type Steps = Record<string, string>;

/** The 12 steps of one Radix export (`gray`, `grayDarkA`, …), in step order. */
function steps(exportName: string): string[] {
  // SAFETY: the Radix module is a flat map of scale name → steps; an unknown
  // name is a typo in SCALES and fails loudly below.
  const scale = (radix as Record<string, Steps | undefined>)[exportName];
  if (!scale) throw new Error(`@radix-ui/colors has no export "${exportName}"`);
  const values = Object.values(scale);
  if (values.length !== 12) {
    throw new Error(`"${exportName}" has ${values.length} steps; expected 12`);
  }
  return values;
}

function scaleLines(name: string): string[] {
  const light = steps(name);
  const dark = steps(`${name}Dark`);
  const lightA = steps(`${name}A`);
  const darkA = steps(`${name}DarkA`);
  return [
    `  /* ${name} */`,
    ...STEPS.map((n, i) => `  --${name}-${n}: light-dark(${light[i]}, ${dark[i]});`),
    ...STEPS.map((n, i) => `  --${name}-a${n}: light-dark(${lightA[i]}, ${darkA[i]});`),
  ];
}

function fixedLines(name: string, exportName: string): string[] {
  const values = steps(exportName);
  return [`  /* ${name} (mode-independent) */`, ...STEPS.map((n, i) => `  --${name}-a${n}: ${values[i]};`)];
}

const header = `/* AUTO-GENERATED by scripts/generate-color-scales.ts from @radix-ui/colors —
   do not edit by hand; run \`pnpm generate-color-scales\`. */`;

const scales = [
  header,
  ``,
  `/* Tier 1: raw scales. Components never read these directly — they read the
   semantic roles in color.css, which are built from them. Each step is a
   light-dark() pair, resolved against the element's color-scheme (see
   color.css for how data-theme sets it). */`,
  `:root {`,
  ...SCALES.flatMap((name, i) => (i === 0 ? scaleLines(name) : [``, ...scaleLines(name)])),
  ``,
  ...fixedLines("black", "blackA"),
  ``,
  ...fixedLines("white", "whiteA"),
  `}`,
  ``,
].join("\n");

const grayTone = [
  header,
  ``,
  `/* Gray tone — swap the neutral gray for one of Radix's tinted grays.

   Every component reads --gray-1…12 / --gray-a1…12 (through the semantic
   roles in color.css). With no data-gray attribute those are the neutral
   Radix gray from scales.css. Setting data-gray on the root — or on any
   subtree — points them at a tinted scale instead:

     <html data-gray="slate">           <Theme gray="slate">

   Tones: mauve (violet-ish), slate (blue-ish), sage (green-ish),
   olive (yellow-green), sand (warm). Each tinted step is itself a
   light-dark() pair, so one alias serves both modes and nested themes. */`,
  ...GRAY_TONES.flatMap((tone) => [
    ``,
    `[data-gray="${tone}"] {`,
    ...STEPS.map((n) => `  --gray-${n}: var(--${tone}-${n});`),
    ...STEPS.map((n) => `  --gray-a${n}: var(--${tone}-a${n});`),
    `}`,
  ]),
  ``,
].join("\n");

await writeFile(path.join(CSS_DIR, "scales.css"), scales);
await writeFile(path.join(CSS_DIR, "gray-tone.css"), grayTone);
console.log(`Wrote ui/src/css/scales.css (${SCALES.length} scales) and ui/src/css/gray-tone.css`);
